"""Set up and verify the public workspace using a local Pub override."""

import argparse
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PRIVATE_MEMBERS = {
    "packages/co_example_ui": "co_example_ui",
    "packages/co_golden_gallery": "co_golden_gallery",
    "packages/open_board/example": "open_board_example",
    "packages/open_epub/example": "open_epub_example",
}
COUI_OVERRIDES = {"coui_core", "coui_flutter", "coui_web"}


def section(lines: list[str], key: str) -> list[str]:
    """Read the indented block under a top-level pubspec key."""
    if f"{key}:" not in lines:
        return []
    body = []
    for line in lines[lines.index(f"{key}:") + 1:]:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line[0].isspace():
            break
        body.append(line)
    return body


def public_overrides(pubspec: str) -> str:
    lines = pubspec.splitlines()
    members = [line.split("#", 1)[0].strip() for line in section(lines, "workspace")]
    if not all(member.startswith("- ") for member in members):
        raise SystemExit("Expected a list of workspace paths in pubspec.yaml.")
    paths = [member.removeprefix("- ").strip() for member in members]
    missing = PRIVATE_MEMBERS.keys() - set(paths)
    if missing:
        raise SystemExit(f"Review the public workspace exclusions for: {', '.join(sorted(missing))}")

    overrides = []
    skip = False
    for line in section(lines, "dependency_overrides"):
        if line.startswith("  ") and not line.startswith("   "):
            key = line.strip().partition(":")[0]
            skip = key in COUI_OVERRIDES
        if not skip:
            overrides.append(line)

    output = ["# Generated by tool/pages/public_workspace.py", "workspace:"]
    output.extend(f"  - {path}" for path in paths if path not in PRIVATE_MEMBERS)
    if overrides:
        output.extend(["dependency_overrides:", *overrides])
    else:
        output.append("dependency_overrides: {}")
    return "\n".join(output) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("scripts", nargs="*", help="Optional Melos scripts to run, e.g. verify")
    args = parser.parse_args()

    override = ROOT / "pubspec_overrides.yaml"
    contents = public_overrides((ROOT / "pubspec.yaml").read_text())
    if override.exists():
        if override.read_text() != contents:
            raise SystemExit("Move your existing pubspec_overrides.yaml aside before public setup.")
    else:
        override.write_text(contents)
    print(f"Public workspace excludes: {', '.join(PRIVATE_MEMBERS.values())}", flush=True)

    if args.scripts:
        subprocess.run(["dart", "pub", "get", "--no-example"], cwd=ROOT, check=True)
        # Melos discovers members from pubspec.yaml. Pass the same exclusions
        # explicitly so that its package scripts follow Pub's local workspace.
        flags = [f"--ignore={name}" for name in PRIVATE_MEMBERS.values()]
        for script in args.scripts:
            subprocess.run(
                ["dart", "run", "melos", "run", script, "--no-select", *flags],
                cwd=ROOT,
                check=True,
            )


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        raise SystemExit(error.returncode) from None
